"""Suggested guard-rail policies. The tool only writes these files; it never applies them.

AWS rejects policy documents with unknown top-level keys, so the "review before applying"
marker lives in every statement's Sid, where it travels with the policy."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ..config import Config
from .files import make_private_dir, write_private

MARKER = "ReviewBeforeApplying"
VERSION = "2012-10-17"
BEARER_ACTIONS = ("bedrock:CallWithBearerToken", "bedrock-mantle:CallWithBearerToken")

FILE_DENY_USERS = "scp-deny-bedrock-to-iam-users.json"
FILE_RESTRICT = "scp-restrict-bedrock-regions-models.json"
FILE_DENY_API_KEYS = "policy-deny-bedrock-api-keys.json"

README = """\
Suggested policies generated by bedrock-audit. REVIEW BEFORE APPLYING.

The tool did not apply any of these and never will. Each statement ID starts with
"ReviewBeforeApplying" so the intent is visible in the AWS console; rename it when you adopt it.
Test every service control policy (SCP) on a sandbox OU before attaching it to production.

{files}
"""

DESCRIPTIONS = {
    FILE_DENY_USERS: (
        "SCP. Denies Amazon Bedrock model invocation to IAM users and to the account root user, "
        "which is where long-lived keys live. IAM roles and Identity Center users are "
        "unaffected. This WILL break any workload still running on IAM user keys, so list those "
        "in scp_exception_principals first."
    ),
    FILE_RESTRICT: (
        "SCP. Denies Amazon Bedrock invocation outside the Regions in bedrock_regions and for "
        "models not in approved_models. Written only when you set at least one of them. "
        "Inference profiles are matched by model ID suffix; application inference profiles are "
        "not covered, so review them separately."
    ),
    FILE_DENY_API_KEYS: (
        "Identity policy (attach to users, groups or roles that should never use Amazon Bedrock "
        "API keys). Denies using any API key through both endpoints, and creating a new "
        "Amazon Bedrock API key."
    ),
}


def deny_iam_users(config: Config) -> dict[str, Any]:
    statement: dict[str, Any] = {
        "Sid": f"{MARKER}DenyBedrockToIamUsers",
        "Effect": "Deny",
        "Action": list(config.invoke_actions),
        "Resource": "*",
        "Condition": {"StringEquals": {"aws:PrincipalType": ["User", "Account"]}},
    }
    if config.scp_exception_principals:
        statement["Condition"]["ArnNotLike"] = {
            "aws:PrincipalArn": list(config.scp_exception_principals)
        }
    return {"Version": VERSION, "Statement": [statement]}


def restrict_regions_and_models(config: Config) -> dict[str, Any] | None:
    statements: list[dict[str, Any]] = []
    if config.bedrock_regions:
        statements.append(
            {
                "Sid": f"{MARKER}DenyBedrockOutsideApprovedRegions",
                "Effect": "Deny",
                "Action": list(config.invoke_actions),
                "Resource": "*",
                "Condition": {
                    "StringNotEquals": {"aws:RequestedRegion": list(config.bedrock_regions)}
                },
            }
        )
    if config.approved_models:
        model_actions = [a for a in config.invoke_actions if a not in BEARER_ACTIONS]
        statements.append(
            {
                "Sid": f"{MARKER}DenyUnapprovedBedrockModels",
                "Effect": "Deny",
                "Action": model_actions,
                "NotResource": _approved_resources(config.approved_models),
            }
        )
    return {"Version": VERSION, "Statement": statements} if statements else None


def _approved_resources(models: tuple[str, ...]) -> list[str]:
    resources: list[str] = []
    for model in models:
        resources.append(f"arn:aws:bedrock:*::foundation-model/{model}")
        resources.append(f"arn:aws:bedrock:*:*:inference-profile/*.{model}")
    return resources


def deny_api_keys() -> dict[str, Any]:
    return {
        "Version": VERSION,
        "Statement": [
            {
                "Sid": f"{MARKER}DenyUsingBedrockApiKeys",
                "Effect": "Deny",
                "Action": list(BEARER_ACTIONS),
                "Resource": "*",
            },
            {
                "Sid": f"{MARKER}DenyCreatingBedrockApiKeys",
                "Effect": "Deny",
                "Action": "iam:CreateServiceSpecificCredential",
                "Resource": "*",
                "Condition": {
                    "StringEquals": {
                        "iam:ServiceSpecificCredentialServiceName": "bedrock.amazonaws.com"
                    }
                },
            },
        ],
    }


def render_all(config: Config) -> dict[str, dict[str, Any]]:
    documents = {FILE_DENY_USERS: deny_iam_users(config)}
    restrict = restrict_regions_and_models(config)
    if restrict is not None:
        documents[FILE_RESTRICT] = restrict
    documents[FILE_DENY_API_KEYS] = deny_api_keys()
    return documents


def write_remediation(directory: Path, config: Config) -> list[str]:
    """Write the documents and a README. Returns the names written."""
    make_private_dir(directory)
    documents = render_all(config)
    for name, document in documents.items():
        write_private(directory / name, json.dumps(document, indent=2) + "\n")
    listing = "\n".join(f"{name}\n    {DESCRIPTIONS[name]}\n" for name in documents)
    if FILE_RESTRICT not in documents:
        listing += (
            f"\n{FILE_RESTRICT} was not written: set bedrock_regions and/or approved_models "
            "in the configuration to generate it.\n"
        )
    write_private(directory / "README.txt", README.format(files=listing))
    return [*documents, "README.txt"]
