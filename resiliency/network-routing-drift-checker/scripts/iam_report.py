"""Write docs/security/iam-report.md: every IAM statement of both synthesized stacks (tasks.md 4.4).

Run after the IAM lint, which synthesizes into infra/cdk.out.test:
    .venv/bin/pytest tests/iam -q && .venv/bin/python scripts/iam_report.py
"""

from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "infra" / "cdk.out.test"
STACKS = {"NetworkRoutingDriftChecker": "Checker stack (networking account)",
          "NetworkRoutingDriftChecker-DevOpsAgentLink": "Link stack (Agent Space account, cross-account only)"}


def _as_list(value):
    return value if isinstance(value, list) else [value]


def _ref(value) -> str:
    """Compact, readable rendering of a CloudFormation resource expression."""
    if isinstance(value, str):
        return value
    if "Ref" in value:
        return f"{{{value['Ref']}}}"
    if "Fn::GetAtt" in value:
        return f"{{{value['Fn::GetAtt'][0]}.{value['Fn::GetAtt'][1]}}}"
    if "Fn::Join" in value:
        return "".join(_ref(v) for v in value["Fn::Join"][1])
    if "Fn::Sub" in value:
        return value["Fn::Sub"] if isinstance(value["Fn::Sub"], str) else value["Fn::Sub"][0]
    return json.dumps(value)


def _owner(policy: dict, template: dict) -> str:
    roles = policy["Properties"].get("Roles") or []
    return ", ".join(_ref(r).strip("{}") for r in roles) or "?"


def rows(template: dict):
    for res in template["Resources"].values():
        if res["Type"] != "AWS::IAM::Policy":
            continue
        condition = res.get("Condition", "always")
        for st in res["Properties"]["PolicyDocument"]["Statement"]:
            cond = ", ".join(sorted(st.get("Condition", {}).get(op, {}).keys().__iter__().__next__()
                                    for op in st.get("Condition", {}))) if st.get("Condition") else ""
            yield (_owner(res, template), condition, ", ".join(sorted(_as_list(st["Action"]))),
                   "<br>".join(_ref(r) for r in _as_list(st["Resource"])), cond)


def trusts(template: dict):
    for lid, res in template["Resources"].items():
        if res["Type"] == "AWS::IAM::Role":
            for st in res["Properties"]["AssumeRolePolicyDocument"]["Statement"]:
                principal = json.dumps(st.get("Principal"))
                keys = sorted(k for op in (st.get("Condition") or {}).values() for k in op)
                yield lid, principal, ", ".join(keys)


def main() -> None:
    lines = ["# IAM report", "",
             "Generated by `scripts/iam_report.py` from the synthesized templates (`cdk synth -c skipBundling=true`).",
             # Explicit `+` (not implicit adjacent-string concatenation) so this reads unambiguously
             # as one list element built from several pieces, and so SAST concat-in-list scanners
             # don't flag it as a possibly-missing comma.
             "The deny-by-default lint in `tests/iam/` checks the same statements against "
             + "`tests/iam/allowlist.json`. `{X}` is a CloudFormation reference; \"Condition\" in the second column "
             + "is the CloudFormation condition the policy exists under (`always`, `HandoffEnabled`, "
             + "`SameAccountHandoff`, `CrossAccountHandoff`).", ""]
    for stack, title in STACKS.items():
        template = json.loads((OUT_DIR / f"{stack}.template.json").read_text())
        lines += [f"## {title}", "", "### Permissions", "",
                  "| Role | Condition | Actions | Resources | Statement conditions |", "|---|---|---|---|---|"]
        lines += [f"| {o} | {c} | {a} | {r} | {k} |" for o, c, a, r, k in sorted(rows(template))]
        lines += ["", "### Trust policies", "", "| Role | Principal | Conditions |", "|---|---|---|"]
        lines += [f"| {lid} | `{p}` | {k} |" for lid, p, k in sorted(trusts(template))]
        managed = [lid for lid, r in template["Resources"].items()
                   if r["Type"] == "AWS::IAM::Role" and r["Properties"].get("ManagedPolicyArns")]
        lines += ["", f"Managed policies attached: {', '.join(managed) or 'none'}.", ""]
    target = ROOT / "docs" / "security" / "iam-report.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
